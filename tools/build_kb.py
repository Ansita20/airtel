def intent(id, title, stage, en_kw, hi_kw, hinglish_kw, en, hi, qr_en, qr_hi, action="NONE",
           points=0, can_bot_resolve=True, money=False, conditions=None, boost=1.0, followup=None):
    d = {
        "id": id,
        "title": title,
        "stage": stage,
        "keywords": {"en": en_kw, "hi": hi_kw, "hinglish": hinglish_kw},
        "answer": {"en": en, "hi": hi},
        "quick_replies": {"en": qr_en, "hi": qr_hi},
        "action": action,
        "base_escalation_points": points,
        "can_bot_resolve": can_bot_resolve,
        "money": money,
        "conditions": conditions or [],
    }
    if boost != 1.0:
        d["boost"] = boost
    if followup:
        d["answer_followup"] = {"en": followup[0], "hi": followup[1]}
    return d


def cond(when, points, reason, counter=None, value=0, force=False):
    c = {"when": when, "points": points, "reason": reason, "value": value, "force_handoff": force}
    if counter:
        c["counter"] = counter
    return c



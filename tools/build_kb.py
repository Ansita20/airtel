"""
Builds app/src/main/assets/help_kb.json for the Udyam Digital help bot.

Edit the INTENTS list below, then run:  python3 tools/build_kb.py
Every intent comes from a drop reason in smb_leads.csv or a catalogue rule (see the
case spec). Placeholders like {monthly_total} are filled by AnswerComposer from the
user's real bundle and RulesEngine results; the bot never invents prices.

Escalation fields:
  base_escalation_points  added whenever this issue is open
  conditions              extra points when something gets worse; force_handoff = the
                          spec says "escalate", so the score is raised to at least 70
  money                   +20 in the scorer (payment, refund, bill dispute)
"""
